/** Manual offline demo command; --check is strictly read-only. */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {randomUUID, createHash} from 'node:crypto';
import {DEMO_ROOT, readDemoSource, safePath, rewritePositions} from './demo-files.mjs';
import {generateNavigation, navigationMismatches} from './navigation.mjs';
import {structuralErrors} from './atlas-validation.mjs';

const serialized = value => JSON.stringify(value, null, 2) + '\n';
const digest = value => createHash('sha256').update(value).digest('hex');
export const RECOVERY_FILE = '.connections-recovery.json';

export function connectionPlan(source) {
  const {dataset, placements} = generateNavigation(source.dataset), changes = new Map();
  const graphText = serialized(dataset.connections);
  if (source.texts.get('connections.json') !== graphText) changes.set('connections.json', graphText);
  for (const [sid, detail] of dataset.detailFiles) {
    const positions = new Map();
    for (const p of placements.filter(p => p.systemId === sid)) positions.set(detail.objects.findIndex(o => o.id === p.gateId), p.position);
    const name = `systems/${sid}.json`, old = source.texts.get(name), next = rewritePositions(old, positions);
    if (old !== next) changes.set(name, next);
  }
  return {dataset, placements, changes};
}

export function checkConnections(source) {
  const plan = connectionPlan(source);
  const errors = [...navigationMismatches(source.dataset, plan.dataset, plan.placements), ...structuralErrors(source.dataset)];
  if (source.texts.get('connections.json') !== serialized(plan.dataset.connections)) errors.push('connections.json: generated bytes/order are stale; run npm run connections');
  return {plan, errors};
}

function validateStaged(source, changes) {
  const proposed = structuredClone(source.dataset);
  for (const [name, text] of changes) {
    const value = JSON.parse(text);
    if (name === 'connections.json') proposed.connections = value;
    else proposed.detailFiles.set(value.id, value);
  }
  const {dataset, placements} = generateNavigation(proposed);
  const errors = [...structuralErrors(proposed), ...navigationMismatches(proposed, dataset, placements)];
  if (errors.length) throw new Error('Staged validation failed:\n' + errors.join('\n'));
}

/** Multi-file replacement with verified backups, not a filesystem transaction.
 * io injection supports failure tests; the CLI always uses Node fs and DEMO_ROOT.
 */
export function writeConnections(source, plan, io = fs) {
  if (!plan.changes.size) return [];
  validateStaged(source, plan.changes);
  const root = io.realpathSync(source.root), journal = path.join(root, RECOVERY_FILE), token = randomUUID();
  if (io.existsSync(journal)) throw new Error(`Pending recovery: ${journal}; inspect docs/NAVIGATION_AUTHORING.md before generating`);
  const records = [...plan.changes].map(([name, next]) => {
    const target = safePath(root, name, io), old = source.texts.get(name);
    return {name, target, old, next, stage: target + `.connections-${token}.tmp`, backup: target + `.connections-${token}.bak`};
  });
  const owned = [], replaced = [];
  const exclusiveWrite = (file, text) => {
    const fd = io.openSync(file, 'wx'); owned.push(file);
    try { io.writeFileSync(fd, text); io.fsyncSync(fd); } finally { io.closeSync(fd); }
    if (io.readFileSync(file, 'utf8') !== text) throw new Error(`Write verification failed: ${file}`);
  };
  const cleanup = () => { for (const file of [...owned].reverse()) if (io.existsSync(file)) io.unlinkSync(file); };
  try {
    // An existing journal blocks a writer; readers/checks never delete it.
    exclusiveWrite(journal, serialized({format: 1, files: records.map(r => ({
      name: r.name, stage: path.relative(root, r.stage), backup: path.relative(root, r.backup),
      previousMissing: r.old === undefined, previousSHA256: r.old === undefined ? null : digest(r.old), nextSHA256: digest(r.next)
    }))}));
    for (const r of records) {
      if (r.old !== undefined) exclusiveWrite(r.backup, r.old);
      exclusiveWrite(r.stage, r.next);
    }
    validateStaged(source, new Map(records.map(r => [r.name, io.readFileSync(r.stage, 'utf8')])));
    // Detect concurrent edits to ALL inputs before the first replacement.
    for (const [name, old] of source.texts) if (io.readFileSync(safePath(root, name, io), 'utf8') !== old) throw new Error(`${name}: changed while generating; no replacement allowed`);
    for (const r of records) {
      safePath(root, r.name, io);
      const current = io.existsSync(r.target) ? io.readFileSync(r.target, 'utf8') : undefined;
      if (current !== r.old) throw new Error(`${r.name}: changed while generating`);
      io.renameSync(r.stage, r.target); replaced.push(r);
    }
    const verified = checkConnections(readDemoSource(root, io));
    if (verified.errors.length) throw new Error(verified.errors.join('\n'));
  } catch (e) {
    const failures = [];
    for (const r of replaced.reverse()) {
      try {
        safePath(root, r.name, io);
        if (io.readFileSync(r.target, 'utf8') !== r.next) throw new Error('file changed after replacement; retained for manual review');
        if (r.old === undefined) io.unlinkSync(r.target);
        else {
          if (io.readFileSync(r.backup, 'utf8') !== r.old) throw new Error('backup verification failed');
          io.copyFileSync(r.backup, r.target);
          if (io.readFileSync(r.target, 'utf8') !== r.old) throw new Error('restore verification failed');
        }
      } catch (restore) { failures.push(`${r.name}: ${restore.message}`); }
    }
    if (!failures.length) { try { cleanup(); } catch (clean) { failures.push(clean.message); } }
    throw new Error(`${e.message}\n${failures.length ? `Recovery required: ${journal}\n${failures.join('\n')}` : 'Previous artifacts retained/restored; no pending recovery.'}\nSee docs/NAVIGATION_AUTHORING.md for recovery instructions.`);
  }
  // Outputs are verified before removing backups. A cleanup failure is reported,
  // retaining the journal when possible; it is not falsely described as rollback.
  try { cleanup(); } catch (e) { throw new Error(`Outputs verified but cleanup failed: ${e.message}. Review ${journal} and docs/NAVIGATION_AUTHORING.md.`); }
  return records.map(r => r.name);
}

export function runConnections({check = false, root = DEMO_ROOT, io = fs} = {}) {
  if (io.existsSync(path.join(root, RECOVERY_FILE))) throw new Error(`Pending recovery: ${RECOVERY_FILE}; inspect docs/NAVIGATION_AUTHORING.md`);
  const source = readDemoSource(root, io);
  if (check) {
    const {errors} = checkConnections(source);
    if (errors.length) throw new Error(errors.join('\n'));
    return ['PASS generated connections and derived gate positions are current (read-only)'];
  }
  const plan = connectionPlan(source);
  const differences = navigationMismatches(source.dataset, plan.dataset, plan.placements);
  const files = writeConnections(source, plan, io);
  return [...differences, ...files.map(name => `UPDATED ${name}`), files.length ? 'PASS generated outputs validated and verified' : 'PASS already current; no files written'];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.slice(2).some(arg => arg !== '--check') || process.argv.length > 3) throw new Error('Usage: node scripts/connections.mjs [--check]; paths are not configurable');
    runConnections({check: process.argv.includes('--check')}).forEach(line => console.log(line));
  } catch (e) { console.error('FAIL', e.message); process.exitCode = 1; }
}
